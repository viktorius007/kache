#!/usr/bin/env python3
"""Behavioral cache oracle: run one isolated case; baseline is expected red.
Run with --direct-only for the green direct-rustc discrimination control.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile

PARSER = argparse.ArgumentParser()
PARSER.add_argument("case", choices=["empty", "locator"])
PARSER.add_argument("--kache", default="/Users/viktor/Developer/github/kache-investigations/coordinator/target/debug/kache")
PARSER.add_argument("--direct-only", action="store_true")
ARGS = PARSER.parse_args()
BASE = Path(__file__).resolve().parent
ROOT = Path(tempfile.mkdtemp(prefix="replay-" + ARGS.case + "-", dir=BASE))
RUSTC = subprocess.check_output(["rustup", "which", "rustc"], text=True).strip()
CACHE = ROOT / "cache"
CACHE.mkdir()
CONFIG = ROOT / "config.toml"
CONFIG.write_text('[cache]\nlocal_only = true\nignore_env = true\nlocal_store = "' + str(CACHE) + '"\nruntime_dir = "' + str(CACHE) + '"\n')
ENV = os.environ.copy()
for key in list(ENV):
    if key.startswith("KACHE_") or key.startswith("CARGO_") or key in ("OUT_DIR", "RUSTC_WRAPPER", "RUSTC_WORKSPACE_WRAPPER", "RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS"):
        ENV.pop(key, None)
ENV.update(KACHE_CONFIG=str(CONFIG), KACHE_CACHE_DIR=str(CACHE),
           KACHE_LOG="kache=trace", KACHE_SCHEDULER="0",
           KACHE_DEFERRED_DISCOVERY="0", RUSTC_WRAPPER="",
           HOST_CC="clang", HOST_CXX="clang++", CC="clang", CXX="clang++")
RESULTS = {"case": ARGS.case, "root": str(ROOT), "direct_only": ARGS.direct_only}

def run(argv, cwd, env, name):
    result = subprocess.run(argv, cwd=cwd, env=env, capture_output=True, text=True, timeout=60)
    (ROOT / (name + ".log")).write_text(result.stdout + result.stderr)
    assert result.returncode == 0, "setup/compile failed: " + name + "\n" + result.stderr
    return result

def compile_lib(cwd, env, name, label, wrapped=True):
    out = cwd / "target/debug/deps"
    out.mkdir(parents=True, exist_ok=True)
    argv = [RUSTC, "--crate-name", name, "--crate-type", "rlib", "--edition", "2021", "--emit=link", "lib.rs", "--out-dir", str(out)]
    if wrapped and not ARGS.direct_only:
        argv.insert(0, ARGS.kache)
    result = run(argv, cwd, env, label)
    return out / ("lib" + name + ".rlib"), result

def observe(cwd, env, name, artifact, label):
    main = cwd / "main.rs"
    expression = name + "::present()" if ARGS.case == "empty" else name + "::BAKED"
    main.write_text('fn main() { println!("{}", ' + expression + '); }\n')
    executable = ROOT / (label + "-consumer")
    run([RUSTC, "--edition=2021", str(main), "--extern", name + "=" + str(artifact), "-o", str(executable)], cwd, env, label + "-consumer-compile")
    return run([str(executable)], cwd, env, label + "-consumer-run").stdout.strip()

if ARGS.case == "empty":
    cwd = ROOT / "checkout"
    cwd.mkdir()
    (cwd / "lib.rs").write_text('pub fn present() -> bool { option_env!("KACHE_AUDIT_SWITCH").is_some() }\n')
    initial_env = ENV.copy()
    artifact, cold = compile_lib(cwd, initial_env, "empty", "cold-unset")
    initial = observe(cwd, initial_env, "empty", artifact, "cold-unset")
    assert initial == "false", "cold control must observe unset"
    artifact, warm = compile_lib(cwd, initial_env, "empty", "warm-unset")
    assert observe(cwd, initial_env, "empty", artifact, "warm-unset") == initial
    if not ARGS.direct_only:
        assert "local cache hit for empty" in warm.stderr, "warm control must be a cache hit"
    changed_env = initial_env.copy()
    changed_env["KACHE_AUDIT_SWITCH"] = ""
    artifact, changed = compile_lib(cwd, changed_env, "empty", "changed-empty")
    cached = observe(cwd, changed_env, "empty", artifact, "changed-empty")
    artifact, direct = compile_lib(cwd, changed_env, "empty", "direct-empty", wrapped=False)
    expected = observe(cwd, changed_env, "empty", artifact, "direct-empty")
    assert expected == "true", "direct control must observe empty as present"
else:
    source = 'macro_rules! include { ($path:expr) => { $path }; }\npub const BAKED: &str = include!(env!("OUT_DIR"));\npub const TEXT: &str = include_str!(concat!(env!("OUT_DIR"), "/data.txt"));\n'
    checkouts = []
    for name in ["checkout_a", "checkout_b"]:
        cwd = ROOT / name
        cwd.mkdir()
        (cwd / "lib.rs").write_text(source)
        out_dir = cwd / "target/debug/build/pkg-deadbeef/out"
        out_dir.mkdir(parents=True)
        (out_dir / "data.txt").write_text("identical generated bytes\n")
        env = ENV.copy()
        env["OUT_DIR"] = str(out_dir)
        checkouts.append((cwd, env))
    first, first_env = checkouts[0]
    artifact, cold = compile_lib(first, first_env, "locator", "cold-a")
    initial = observe(first, first_env, "locator", artifact, "cold-a")
    assert initial == first_env["OUT_DIR"], "cold control must embed producer OUT_DIR"
    artifact, warm = compile_lib(first, first_env, "locator", "warm-a")
    assert observe(first, first_env, "locator", artifact, "warm-a") == initial
    if not ARGS.direct_only:
        assert "local cache hit for locator" in warm.stderr, "warm control must hit"
    second, changed_env = checkouts[1]
    artifact, changed = compile_lib(second, changed_env, "locator", "changed-b")
    cached = observe(second, changed_env, "locator", artifact, "changed-b")
    artifact, direct = compile_lib(second, changed_env, "locator", "direct-b", wrapped=False)
    expected = observe(second, changed_env, "locator", artifact, "direct-b")
    assert expected == changed_env["OUT_DIR"], "direct control must embed consumer OUT_DIR"
RESULTS.update(initial=initial, cached=cached, direct=expected,
               changed_cache_hit=("local cache hit for " in changed.stderr))
(ROOT / "results.json").write_text(json.dumps(RESULTS, indent=2) + "\n")
print(json.dumps(RESULTS, indent=2), flush=True)
assert cached == expected, "ASSERTION key oracle violated: cached=" + repr(cached) + " direct=" + repr(expected)
print("PASS: cached observation matches direct compiler")
